export interface PIISelfTestResult {
  passed: number
  failed: number
  negatives: { total: number; falsePositives: number }
  positives: { total: number; missed: number }
  details: string[]
}

export function runPIISelfTest(): PIISelfTestResult {
  const details: string[] = []
  let fp = 0
  let missed = 0
  for (const t of PII_NEGATIVES) {
    const hits = scanPII(t)
    if (hits.length) {
      fp++
      details.push(`오탐: "${t}" → ${hits.map((h) => `${h.kind}:${h.text}`).join(', ')}`)
    }
  }
  for (const p of PII_POSITIVES) {
    const hits = scanPII(p.text)
    if (!hits.some((h) => h.kind === p.kind)) {
      missed++
      details.push(`놓침(${p.kind}): "${p.text}" → ${hits.map((h) => `${h.kind}:${h.text}`).join(', ') || '없음'}`)
    }
  }
  const total = PII_NEGATIVES.length + PII_POSITIVES.length
  return {
    passed: total - fp - missed,
    failed: fp + missed,
    negatives: { total: PII_NEGATIVES.length, falsePositives: fp },
    positives: { total: PII_POSITIVES.length, missed },
    details,
  }
}
